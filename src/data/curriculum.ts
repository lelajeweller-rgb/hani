function buildLesson(
  moduleId: number,
  lessonIdx: number,
  difficulty: 'Beginner' | 'Intermediate' | 'Advanced',
  bp: TopicBlueprint
): LessonContent {
  const defaultSteps = [
    `Read the problem statement and identify how ${bp.title} models the data or control flow.`,
    'Write clean Python 3 syntax paying close attention to colons (:) and 4-space indentation.',
    'Execute the code in the Pyodide Playground and inspect each line of printed output.',
    'Test edge cases (empty values, zero, boundary inputs) as expected in B.Tech lab evaluations.',
  ];

  return {
    id: `m${moduleId}-l${lessonIdx + 1}`,
    moduleId,
    title: bp.title,
    durationMinutes: difficulty === 'Beginner' ? 10 : difficulty === 'Intermediate' ? 14 : 18,
    difficulty,
    introduction: bp.intro,
    localizedKeyTakeaway: makeLocalizedNote(bp.title, bp.simple),
    simpleExplanation: bp.simple,
    realLifeExample: bp.realLife,
    syntax: bp.syntax,
    workingCode: bp.code,
    expectedOutput: bp.output,
    stepByStep: bp.steps || defaultSteps,
    commonMistakes: [
      {
        wrong: bp.mistakeWrong,
        right: bp.mistakeRight,
        reason: bp.mistakeReason,
      },
    ],
    practiceQuestions: [
      `Write a clean Python 3 program demonstrating ${bp.title} using your own college roll number or branch data.`,
      `Explain ${bp.title} in 3–4 sentences with syntax and an example as asked in a 5-mark B.Tech university question.`,
      `Modify the working code above to handle an additional user case and verify its output in the Coding Playground.`,
    ],
    miniTest: [
      {
        question: bp.quizQ,
        options: bp.quizOptions,
        correctIndex: bp.quizAns,
        explanation: bp.quizExp,
      },
    ],
  };
}

